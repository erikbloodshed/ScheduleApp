using System.Collections;
using System.Collections.ObjectModel;
using System.Collections.Specialized;
using System.ComponentModel;
using System.Reflection;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Input;
using System.Windows.Media;

namespace ScheduleApp.Desktop.Controls.FlexGrid;

/// <summary>
/// Prototype custom control in the shape of MESCIUS FlexGrid: bound columns, click-to-sort
/// headers, drag-to-resize columns, row selection (single/extended, click/ctrl/shift, and
/// arrow-key navigation), and in-cell editing (double-click or F2, commit on Enter/Tab,
/// cancel on Escape) -- all over a row-virtualizing panel so a large ItemsSource doesn't
/// realize a visual per row. Not wired into any real view; see FlexGridPrototypeWindow for
/// a runnable demo.
///
/// Cell values are read/written by reflection off <see cref="FlexGridColumn.BindingPath"/>
/// (see FlexGridReflection) rather than through WPF's Binding engine -- there's no
/// per-item container for a Binding's DataContext to hang off, since rows are realized and
/// recycled as plain visuals by FlexGridRowsPanel, not generated by an ItemsControl. That
/// also means an external change to an item's property (nothing routed through this grid)
/// isn't picked up until that row is next realized -- acceptable for a prototype, not for
/// production use against externally-mutated data.
///
/// <para><b>Unbound mode</b> -- FlexGrid's own way of working without a DataSource at all,
/// for data that's naturally cell-based rather than a list of objects (a manually-built
/// summary grid, a small spreadsheet-like editor). Active whenever <see cref="ItemsSource"/>
/// is null: set <see cref="RowCount"/> (or call <see cref="AddRow"/>/<see cref="InsertRow"/>/
/// <see cref="RemoveRow"/>) and read/write cells directly through the <c>this[row, column]</c>
/// indexer -- <see cref="FlexGridColumn.BindingPath"/> isn't needed, and
/// <see cref="FlexGridColumn.DataType"/> takes its place for choosing an editor and parsing
/// typed input. The two modes are mutually exclusive: the unbound members throw
/// InvalidOperationException while ItemsSource is set, and setting ItemsSource clears
/// whatever unbound data was there.</para>
/// </summary>
public partial class FlexDataGrid : UserControl
{
    private readonly FlexGridColumnHeadersPresenter _headerPresenter;
    private readonly FlexGridRowsPanel _rowsPanel;
    private readonly List<object> _items = [];
    private readonly FlexGridUnboundStore _unboundStore = new();
    private readonly HashSet<int> _selectedIndices = [];

    private FlexGridColumn? _sortColumn;
    private ListSortDirection _sortDirection = ListSortDirection.Ascending;
    private int _currentRowIndex = -1;
    private int _currentColumnIndex = -1;

    public FlexDataGrid()
    {
        InitializeComponent();

        Columns = [];
        Columns.CollectionChanged += OnColumnsChanged;

        // Two brushes from one accent colour, and they have to differ: the selected row
        // fills with the translucent one (so the cell text underneath stays readable) and
        // the current cell outlines itself with the opaque one. Using a single brush for
        // both -- as this did originally -- draws the current-cell border in exactly the
        // colour of the row highlight it sits on, i.e. invisibly.
        var accent = (TryFindResource("SystemAccentColorPrimaryBrush") as SolidColorBrush)?.Color
                     ?? Color.FromRgb(0x3B, 0x82, 0xF6);

        SelectionBrush = Freeze(new SolidColorBrush(Color.FromArgb(0x38, accent.R, accent.G, accent.B)));
        CurrentCellBrush = Freeze(new SolidColorBrush(accent));

        _headerPresenter = new FlexGridColumnHeadersPresenter(this);
        HeaderHost.Child = _headerPresenter;

        _rowsPanel = new FlexGridRowsPanel(this);
        BodyScrollViewer.Content = _rowsPanel;

        PreviewKeyDown += OnPreviewKeyDown;
    }

